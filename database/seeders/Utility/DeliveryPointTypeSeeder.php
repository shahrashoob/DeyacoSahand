     * تحویل در محل مشتری (Delivered at Place - DAP):
     * بار تا محل مشخص‌شده مشتری حمل شده و تحویل داده می‌شود، اما هزینه تخلیه به عهده مشتری است.
     *
     * تحویل در محل مشتری همراه با تخلیه (Delivered Duty Paid - DDP):
