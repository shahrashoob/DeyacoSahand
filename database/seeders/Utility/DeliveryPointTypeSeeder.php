     * بار تا یک نقطه واسطه (مثلاً انبار، پایانه یا مرکز توزیع) ارسال شده و تحویل داده می‌شود، سپس مشتری خود بار را از آنجا دریافت می‌کند.
     *
     * تحویل در محل بارگیری کارخانه (Free On Board - FOB):
     * بار روی وسیله نقلیه در کارخانه بارگیری شده و مسئولیت از آنجا به بعد به خریدار منتقل می‌شود.
     *
     * این اصطلاحات و نوع تحویل معمولاً در قراردادهای تجاری و قوانین حمل‌ونقل (مثل اینکوترمز Incoterms) مشخص می‌شوند. اگر نیاز داری جزییات بیشتر یا اصطلاحات دقیق‌تری بر اساس شرایط خاصت داشته باشی، بگو تا کمک کنم.
 */
